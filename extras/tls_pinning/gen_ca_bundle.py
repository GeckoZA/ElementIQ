#!/usr/bin/env python3
"""Regenerate include/ca_bundle.h: a small, pinned set of root CAs used to verify
the TLS connection to GitHub (api.github.com + release asset CDN) for OTA.

Roots come from the Mozilla store via the `certifi` package (pip install certifi cryptography).
Edit ROOTS below to add/remove roots, then run:  python3 gen_ca_bundle.py

Why not the full ESP-IDF bundle? It is ~60 KB of flash; this set is ~10 KB.
If GitHub ever moves to a root that is not listed, OTA fails closed with a TLS error
(it never falls back to unverified TLS) - add the root here and ship a firmware update
(or upload the new .bin through the web UI).
"""
import re, sys, os
import certifi
from cryptography import x509

ROOTS = [
    "DigiCert Global Root G2",
    "DigiCert Global Root G3",
    "USERTrust RSA Certification Authority",
    "USERTrust ECC Certification Authority",
    "ISRG Root X1",
    "Microsoft RSA Root Certificate Authority 2017",
    "Microsoft ECC Root Certificate Authority 2017",
]

pem = open(certifi.where()).read()
found = {}
for c in re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", pem, re.S):
    cn = x509.load_pem_x509_certificate(c.encode()).subject.rfc4514_string()
    for r in ROOTS:
        if ("CN=" + r + ",") in cn + ",":
            found[r] = c.strip()
missing = [r for r in ROOTS if r not in found]
if missing:
    sys.exit("missing roots: %s" % missing)

out = ["// AUTO-GENERATED by tools/gen_ca_bundle.py - do not edit by hand.",
       "// Pinned root CAs for OTA TLS verification (see the script for the rationale).",
       "#pragma once", "",
       "static const char OTA_CA_BUNDLE[] =", ""]
for r in ROOTS:
    out.append("// " + r)
    for line in found[r].splitlines():
        out.append('"%s\\n"' % line)
    out.append("")
out[-1] = ";"
path = os.path.join(os.path.dirname(__file__), "ca_bundle.h")
open(path, "w").write("\n".join(out) + "\n")
print("wrote", os.path.normpath(path), "-", len(ROOTS), "roots")
