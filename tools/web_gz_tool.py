#!/usr/bin/env python3
"""Work with the gzip-embedded web pages in src/generated/web_gz.inc.
Flash is tight, so pages stay stored compressed in firmware; this tool lets you edit them as HTML.

  python3 tools/web_gz_tool.py extract OUTDIR          # write OUTDIR/<page>.html for every page
  python3 tools/web_gz_tool.py pack INDIR              # re-compress every INDIR/<page>.html back into web_gz.inc

Page names are the GZ_PAGE_<NAME> symbols, lower-cased (home, settings, about, portal, login, ...).
web_src/login.html and web_src/portal.html are the current sources of the login page and the
first-time-setup wizard.
"""
import re, gzip, sys, os
INC = os.path.join(os.path.dirname(__file__), "..", "src", "generated", "web_gz.inc")
PAT = re.compile(r"const uint8_t GZ_PAGE_(\w+)\[\] PROGMEM = \{([^}]*)\};\s*const size_t GZ_PAGE_\w+_LEN = \d+;")

def pages(src):
    for m in PAT.finditer(src):
        yield m.group(1), gzip.decompress(bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", m.group(2)))).decode()

def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("extract", "pack"):
        sys.exit(__doc__)
    cmd, d = sys.argv[1], sys.argv[2]
    src = open(INC).read()
    if cmd == "extract":
        os.makedirs(d, exist_ok=True)
        for n, h in pages(src):
            open(os.path.join(d, n.lower() + ".html"), "w").write(h)
            print("extracted", n.lower(), len(h), "bytes")
        return
    out = ["// Auto-generated by tools/web_gz_tool.py", "#pragma once", "#include <Arduino.h>", ""]
    total = 0
    for n, old in pages(src):
        f = os.path.join(d, n.lower() + ".html")
        html = open(f).read() if os.path.exists(f) else old
        gz = gzip.compress(html.encode(), 9, mtime=0)
        total += len(gz)
        out += ["const uint8_t GZ_PAGE_%s[] PROGMEM = {%s};" % (n, ",".join("0x%02x" % c for c in gz)),
                "const size_t GZ_PAGE_%s_LEN = %d;" % (n, len(gz)), ""]
        print("packed", n.lower(), len(html), "->", len(gz))
    open(INC, "w").write("\n".join(out))
    print("total compressed bytes:", total)

main()
